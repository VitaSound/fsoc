#!/usr/bin/env python3
"""Generate golden ISA reference images.

Offline tool: assembles tests/golden-src/<arch>/programs.4th and records the
resulting byte images in tests/golden/<arch>.json with a `generator` field
naming the toolchain. In CI/fmix test only the committed static golden is
used — external toolchains are never a runtime test dependency.

Two modes:
  --bootstrap   assemble with the fsoc fasm (gforth) and record the result.
                Used to seed the committed golden when no external assembler
                is installed.
  --external    assemble with an external toolchain (sdas8051 / avr-gcc /
                z80asm). This is the authoritative reference that can catch
                fsoc bugs; it is offline-only and requires the tools.

The programs.4th driver emits lines of the form:
    IMAGE <name> <hex> <hex> ...
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# External assembler per arch: (command, version-flag). sdas8051 ships with
# SDCC; the version is captured from the command's -V/--version output.
EXTERNAL = {
    "mcs51": ["sdas8051"],
    "avr": ["avr-gcc"],
    "z80": ["z80asm"],
}


def assemble_bootstrap(arch: str) -> dict:
    """Assemble programs.4th with the fsoc fasm and parse the IMAGE lines."""
    src = ROOT / f"tests/golden-src/{arch}/programs.4th"
    if not src.exists():
        raise SystemExit(f"no golden source: {src}")
    import os
    env = dict(os.environ)
    env["FSOC_HOME"] = str(ROOT)
    proc = subprocess.run(
        ["gforth", str(src)], capture_output=True, text=True, env=env
    )
    out = proc.stdout + proc.stderr
    if proc.returncode != 0:
        raise SystemExit(f"gforth failed ({proc.returncode}):\n{out}")

    images = {}
    for line in out.splitlines():
        if not line.startswith("IMAGE "):
            continue
        parts = line.split()
        name = parts[1]
        hexes = parts[2:]
        images[name] = "".join(hexes)
    if not images:
        raise SystemExit("no IMAGE lines emitted")
    return images


def external_version(arch: str) -> str:
    cmd = EXTERNAL.get(arch, [arch])
    try:
        proc = subprocess.run(
            [cmd[0], "--version"], capture_output=True, text=True, timeout=10
        )
        return (proc.stdout or proc.stderr or "?").strip().splitlines()[0]
    except Exception:
        return "unknown"


def main():
    if len(sys.argv) < 2:
        print(
            "usage: gen_golden.py <arch> [--external]\n"
            "  default (no flag) records the fsoc bootstrap golden.\n"
            "  --external uses the external assembler (offline-only)."
        )
        sys.exit(1)

    arch = sys.argv[1]
    mode = "--external" if "--external" in sys.argv else "--bootstrap"

    if mode == "--external":
        raise SystemExit(
            "external golden generation requires the offline toolchain "
            f"({', '.join(EXTERNAL.get(arch, ['<none>']))}); "
            "run it where the assembler is installed."
        )

    images = assemble_bootstrap(arch)
    generator = f"bootstrap: fsoc fasm (gforth) — seed before external run"

    golden = {
        "arch": arch,
        "generator": generator,
        "images": [
            {"name": name, "bytes": hexstr}
            for name, hexstr in sorted(images.items())
        ],
    }

    out = ROOT / f"tests/golden/{arch}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(golden, indent=2) + "\n")
    print(f"wrote {out} ({len(images)} images)")

    # Emit a Forth include so golden_test.4th can hex-diff without a JSON
    # parser. One golden:NAME 2constant per image, holding the hex string.
    ft = ROOT / f"tests/golden/{arch}-golden.4th"
    lines = [
        f"\\ tests/golden/{arch}-golden.4th — auto-generated by gen_golden.py.",
        f"\\ Do not edit; regenerate with `python3 tools/gen_golden.py {arch}`.",
        "",
    ]
    for item in golden["images"]:
        name = item["name"]
        hexstr = item["bytes"]
        lines.append(f's" {hexstr}" 2constant golden:{name}')
    ft.write_text("\n".join(lines) + "\n")
    print(f"wrote {ft}")


if __name__ == "__main__":
    main()
